#!/usr/bin/env node
/*
 * Builds the Timer tab's drop-in block.
 *
 * MixMatch.html is a single file, so the tab cannot `import` anything — but
 * developing against a hand-inlined copy of the engine would mean editing the
 * game in two places and diffing them forever, which is the same failure mode
 * the token fixtures exist to prevent.
 *
 * So timer-tab.html is the source (it imports timer-engine.js like a normal
 * module and can be opened directly in a browser), and this script produces
 * timer-tab.inline.html: the same block with the engine inlined and the import
 * removed. CI regenerates it and fails on a diff, so the pasteable artifact
 * can never quietly fall behind the tested engine.
 *
 * Same idea as rocketman/tools/build-single-file.mjs, one project over.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'web');
const SOURCE = join(web, 'timer-tab.html');
const ENGINE = join(web, 'timer-engine.js');
const OUT = join(web, 'timer-tab.inline.html');
/** The iPad app's bundled page. Same block, wrapped in a document sized for a
 *  full screen instead of a page — so the app can never drift from the web. */
const APP_OUT = join(root, 'ios', 'MixMatch.swiftpm', 'Resources', 'index.html');

const BEGIN = 'MM-TIMER-TAB:BEGIN';
const END = 'MM-TIMER-TAB:END';
const IMPORT = /^import \{[\s\S]*?\} from '\.\/timer-engine\.js';\n/m;

function fail(message) {
  console.error(`build-timer-tab: ${message}`);
  process.exit(1);
}

const [page, engine] = await Promise.all([readFile(SOURCE, 'utf8'), readFile(ENGINE, 'utf8')]);

const from = page.indexOf(BEGIN);
const to = page.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  fail(`could not find the ${BEGIN} / ${END} markers in timer-tab.html`);
}

// Take the whole comment that opens the block and everything up to the closing
// marker's comment, so the pasteable file keeps its own instructions.
const blockStart = page.lastIndexOf('<!--', from);
const blockEnd = page.indexOf('-->', to) + 3;
const block = page.slice(blockStart, blockEnd);

if (!IMPORT.test(block)) {
  fail("could not find the `import { ... } from './timer-engine.js';` statement");
}

// `export` is the only module syntax the engine uses, and only ever at the
// start of a line. Stripping it turns the module into a script body that runs
// unchanged inside the block's existing IIFE-adjacent module scope.
const inlined = engine.replace(/^export /gm, '');
if (/\b(?:import|export)\b\s*[{*]/.test(inlined)) {
  fail('the engine grew module syntax this script does not know how to inline');
}

const banner = [
  '// ────────────────────────────────────────────────────────────────────────',
  '// GENERATED — do not edit. Source: mixmatch/web/timer-engine.js',
  '// Regenerate with: npm run mixmatch:timer',
  '// ────────────────────────────────────────────────────────────────────────',
  '',
].join('\n');

const built = block.replace(IMPORT, banner + inlined + '\n');

const header = `<!-- GENERATED by mixmatch/tools/build-timer-tab.mjs — do not edit by hand.
     Source: mixmatch/web/timer-tab.html + mixmatch/web/timer-engine.js
     Regenerate with: npm run mixmatch:timer

     Paste everything below into MixMatch.html where the Timer tab body goes.
-->\n`;

await writeFile(OUT, header + built + '\n', 'utf8');

/*
 * The iPad app's page.
 *
 * Deliberately the same generated block: an app that carried its own copy of
 * the game would be a second thing to keep in step, and the whole reason this
 * script exists is that copies drift. WKWebView serves it from a custom scheme
 * (see WebHost.swift), so it gets a real origin and localStorage survives.
 */
const appPage = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no">
<title>Mix &amp; Match</title>
<link rel="icon" href="data:,">
<style>
  html,body{margin:0;height:100%;background:#241F19;color:#F6EFE2;
    font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;
    -webkit-text-size-adjust:100%;
    /* A game played by dragging a finger: the OS must not read that as a text
       selection, a callout, or a rubber-band scroll. */
    -webkit-user-select:none;user-select:none;-webkit-touch-callout:none;
    overscroll-behavior:none}
  .app{min-height:100%;display:flex;align-items:center;justify-content:center;
    padding:max(16px,env(safe-area-inset-top)) max(14px,env(safe-area-inset-right))
            max(16px,env(safe-area-inset-bottom)) max(14px,env(safe-area-inset-left))}
  /* App-only: inside MixMatch the tab sits in a column with everything else and
     560px is right. Here it is the whole screen, and an iPad has room for a
     bigger playfield. Overriding from the page rather than from the block keeps
     the pasteable drop-in byte-identical on both. */
  .app .mmt{max-width:min(720px,100%);width:100%}
</style>
</head>
<body>
<div class="app">
${built}
</div>
</body>
</html>
`;

await mkdir(dirname(APP_OUT), { recursive: true });
await writeFile(APP_OUT, appPage, 'utf8');

const kb = (Buffer.byteLength(header + built) / 1024).toFixed(1);
console.log(`wrote ${OUT} (${kb} KB, no assets, no network)`);
console.log(`wrote ${APP_OUT}`);
